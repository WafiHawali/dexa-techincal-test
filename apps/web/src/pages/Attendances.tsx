import { useQuery } from '@tanstack/react-query';
import { useState } from 'react';
import { useParams, useSearchParams } from 'react-router';
import { AttendanceTable } from '../components/AttendanceTable';
import { ProtectedPhoto } from '../components/ProtectedPhoto';
import { Badge, Card, Detail, Empty, ErrorPanel, Loading, PageHeader, Pagination, SearchInput, useDebounce } from '../components/ui';
import { attendanceApi } from '../lib/api';
import { formatDate, formatTime, initials } from '../lib/dates';

export function Attendances() {
  const [params, setParams] = useSearchParams();
  const [search, setSearch] = useState(params.get('search') || '');
  const debounced = useDebounce(search);
  const date = params.get('date') || '';
  const rawPage = Number(params.get('page') || 1);
  const page = Number.isInteger(rawPage) && rawPage > 0 ? rawPage : 1;
  const pageSize = 15;
  const query = useQuery({ queryKey: ['attendances', 'list', debounced, date, page, pageSize], queryFn: () => attendanceApi.list({ search: debounced || undefined, date: date || undefined, page, pageSize }) });
  function update(values: Record<string, string>) {
    setParams((previous) => {
      const next = new URLSearchParams(previous);
      Object.entries(values).forEach(([key, value]) => value ? next.set(key, value) : next.delete(key));
      return next;
    }, { replace: true });
  }
  return <>
    <PageHeader title="Attendance monitor" description="Review employee check-ins, clock-outs, and photo evidence in Asia/Jakarta time." />
    <p className="mb-5 text-xs text-slate-600">Attendance records are read-only.</p>
    <Card>
      <div className="flex flex-wrap items-center justify-between gap-4 border-b border-slate-200 p-5">
        <SearchInput value={search} onChange={(value) => { setSearch(value); update({ search: value, page: '' }); }} placeholder="Search employee name or number…" />
        <div className="flex flex-wrap items-center gap-3">
          <label htmlFor="attendance-date" className="text-xs font-medium text-slate-600">Date</label>
          <input id="attendance-date" type="date" value={date} className="input w-auto" onChange={(e) => update({ date: e.target.value, page: '' })} />
          {(search || date) && <button type="button" className="min-h-11 text-xs font-semibold text-brand-800 hover:text-brand-900" onClick={() => { setSearch(''); setParams({}, { replace: true }); }}>Clear filters</button>}
        </div>
      </div>
      {query.isPending ? <Loading /> : query.isError ? <div className="p-5"><ErrorPanel error={query.error} retry={() => void query.refetch()} /></div> : <><AttendanceTable items={query.data.items} hrd /><Pagination page={page} pageSize={pageSize} total={query.data.total} onChange={(next) => update({ page: String(next) })} /></>}
    </Card>
  </>;
}

export function AttendanceDetail() {
  const { id } = useParams();
  const query = useQuery({ queryKey: ['attendances', 'detail', id], queryFn: () => attendanceApi.get(id!), enabled: !!id });
  if (query.isPending) return <Loading label="Loading attendance details…" />;
  if (query.isError) return <><PageHeader title="Attendance detail" back="/hrd/attendances" /><ErrorPanel error={query.error} retry={() => void query.refetch()} /></>;
  const item = query.data;
  const employee = item.employee;
  return <>
    <PageHeader title="Attendance detail" description={`${formatDate(item.attendanceDate, true)}. Check-in ${formatTime(item.checkInAt)} WIB${item.checkOutAt ? `. Check-out ${formatTime(item.checkOutAt)} WIB.` : '.'}`} back="/hrd/attendances" action={<Badge value={item.status} />} />
    <div className="grid items-start gap-6 xl:grid-cols-[1fr_1.1fr]">
      <div className="space-y-5">
        <Card className="p-6">
          <div className="flex items-center gap-4"><span className="avatar h-14 w-14 text-lg">{initials(employee?.fullName)}</span><div><h2 className="text-lg font-semibold text-ink">{employee?.fullName || 'Employee'}</h2><p className="mt-1 text-xs text-slate-600">{employee?.employeeNumber || item.employeeId}</p></div></div>
          <dl className="mt-6 grid grid-cols-2 gap-6 border-t border-slate-200 pt-6">
            <Detail label="Department">{employee?.department}</Detail>
            <Detail label="Position">{employee?.position}</Detail>
            <Detail label="Attendance date">{formatDate(item.attendanceDate)}</Detail>
            <Detail label="Check-in">{formatTime(item.checkInAt)} WIB</Detail>
            <Detail label="Check-out">{item.checkOutAt ? `${formatTime(item.checkOutAt)} WIB` : 'Not set'}</Detail>
            <Detail label="Work email">{employee?.email}</Detail>
            <Detail label="Attendance ID"><span className="font-mono text-xs tabular-nums">{item.id}</span></Detail>
          </dl>
        </Card>
        <p className="rounded-lg border border-slate-200 bg-slate-50 p-4 text-xs leading-6 text-slate-700">Check-in and check-out timestamps are generated by the server and cannot be edited here.</p>
      </div>
      <Card className="overflow-hidden">
        <div className="flex items-center justify-between border-b border-slate-200 p-6"><h2 className="font-semibold text-ink">Attendance evidence</h2><span className="text-xs text-slate-600 tabular-nums">{item.photos?.length || 0} photos</span></div>
        {item.photos?.length ? <div className="divide-y divide-slate-200">{item.photos.map((photo, index) => <figure key={photo.id}><ProtectedPhoto id={photo.id} alt={`${photo.kind === 'CHECK_OUT' ? 'Clock-out' : 'Clock-in'} evidence for ${employee?.fullName || 'employee'} on ${formatDate(item.attendanceDate)}, photo ${index + 1}`} /><figcaption className="px-5 py-4 text-xs text-slate-600">{photo.kind === 'CHECK_OUT' ? 'Clock-out evidence' : 'Clock-in evidence'}. Open the photo for full size.</figcaption></figure>)}</div> : <Empty title="No photo available" description="No photo metadata was returned for this attendance record." />}
      </Card>
    </div>
  </>;
}
